from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SRC = HERE / "styles.json"
STYLES_DIR = ROOT / "styles"
CORE_DIR = ROOT / "core"

HEADER_MD = "<!-- generated by scripts/build_styles.py from scripts/styles.json; do not edit by hand -->"
HEADER_TS = "// generated by scripts/build_styles.py from scripts/styles.json; do not edit by hand"

# 每类推荐的动效（与 motion-lib/INDEX.md 的 slug 对应）
RECOMMEND = {
    "tech": ["number-accent", "ui-flow", "typewriter-copy"],
    "data": ["context-then-value", "checklist-trend", "flow-dots"],
    "board": ["draw-path", "sweep-highlight", "leader-line"],
    "print": ["fore-back-title", "result-hold", "sweep-highlight"],
    "craft": ["holo-reveal", "slow-push", "fore-back-title"],
    "cartoon": ["pulse-cells", "drag-relink", "geometric-wipe"],
    "dimension": ["dual-merge", "draw-path", "node-connect"],
    "film": ["result-first-frame", "counter-roll", "geometric-wipe"],
    "light": ["flow-dots", "equalizer-bars", "node-connect"],
    "evidence": ["scan-zones", "leader-line", "playhead-frames"],
    "paint": ["holo-reveal", "slow-push", "image-relay"],
    "geometry": ["pulse-cells", "dual-merge", "result-hold"],
}


def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb2hex(rgb):
    return "#" + "".join(f"{max(0, min(255, round(v))):02X}" for v in rgb)


def mix(a, b, ratio):
    """a 向 b 混合，ratio 是 b 的占比。"""
    ra, rb = hex2rgb(a), hex2rgb(b)
    return rgb2hex(tuple(ra[i] * (1 - ratio) + rb[i] * ratio for i in range(3)))


def build_full(s, data):
    cats = {c["id"]: c for c in data["categories"]}
    defs = data["categoryDefaults"][s["cat"]]
    fam = data["fontFamilies"]
    cat = cats[s["cat"]]
    fkeys = defs["fonts"]

    palette = {
        "bg": s["bg"],
        "surface": s["surface"],
        "surface2": mix(s["surface"], s["text"], 0.10),
        "text": s["text"],
        "dim": mix(s["text"], s["bg"], 0.45),
        "accent": s["accent"],
        "accent2": s["accent2"],
        "line": mix(s["text"], s["bg"], 0.12),
        "problem": "#FF5C5C",
    }
    fonts = {
        "display": fam[fkeys[0]],
        "body": fam[fkeys[1]],
        "mono": fam[fkeys[2]],
        "weight": defs["weight"],
        "tracking": defs["tracking"],
    }
    stage = {
        "type": defs["stage"],
        "typeCn": data["stageTypes"][defs["stage"]],
        "texture": s["tex"],
        "grid": 48 if defs["stage"] in ("grid", "toy") else 0,
        "glow": s["accent"],
        "vignette": 0.50 if defs["stage"] in ("grid", "glow", "scanlines", "film", "lens") else 0.16,
    }
    motion = {
        "feel": s["feel"],
        "easing": defs["easing"],
        "spawn": defs["spawn"],
        "density": defs["density"],
        "fps": 30,
    }
    return {
        "slug": s["slug"],
        "cn": s["cn"],
        "en": s["en"],
        "cat": s["cat"],
        "catCn": cat["cn"],
        "catEn": cat["en"],
        "signature": s["sig"],
        "palette": palette,
        "fonts": fonts,
        "stage": stage,
        "motion": motion,
        "camera": s["cam"],
        "goodFor": s["good"],
        "badFor": s["bad"],
        "triggers": s["trig"],
        "invariants": s["inv"],
        "pitfalls": s["pit"],
        "recommendedMotions": RECOMMEND[s["cat"]],
    }


def render_style_md(f):
    p = f["palette"]
    fo = f["fonts"]
    st = f["stage"]
    mo = f["motion"]
    rec = "、".join(f"`{x}`" for x in f["recommendedMotions"])
    rows = "\n".join(f"| {k} | `{v}` |" for k, v in [
        ("背景 bg", p["bg"]), ("面板 surface", p["surface"]), ("面板提亮 surface2", p["surface2"]),
        ("主文字 text", p["text"]), ("次级文字 dim", p["dim"]), ("主强调 accent", p["accent"]),
        ("次强调 accent2", p["accent2"]), ("分隔线 line", p["line"]), ("问题色 problem", p["problem"]),
    ])
    inv = "\n".join(f"- {x}" for x in f["invariants"])
    pit = "\n".join(f"- {x}" for x in f["pitfalls"])
    good = "、".join(f["goodFor"])
    bad = "、".join(f["badFor"])
    trig = "、".join(f["triggers"])
    return f"""# {f['cn']} — {f['en']} · Style Prompt

> {f['signature']}
>
> 分类 **{f['catCn']} / {f['catEn']}** ｜ 底板 `{st['type']}`（{st['typeCn']}）｜ 推荐搭配动效：{rec}

{HEADER_MD}

## 1. 它是什么，不是什么

{f['signature']}
一套画风 = 一整支片统一的视觉语言；它**不规定具体动作**，动作由 `motion-lib/` 的 31 个效果提供，两者正交组合。

**不是**：不是可复用的单个动效组件，不是模板换字，不是把别的风格提示词复制过来。

## 2. 色板

| 用途 | 色值 |
|---|---|
{rows}

> 色板是硬约束。**主强调色全片只服务于最重要的元素**，出现第二个同等权重的强调色就是错的。

## 3. 字体与排版

- 标题：`{fo['display']}`，字重 `{fo['weight']}`，字距 `{fo['tracking']}`
- 正文：`{fo['body']}`
- 数字 / 标注：`{fo['mono']}`
- 字体栈全部是系统字体，**不加载外部字体文件、不新增 npm 依赖**。

## 4. 底板与材质

- 底板类型：`{st['type']}` — {st['typeCn']}
- 材质：{st['texture']}
- 网格模数：{st['grid'] if st['grid'] else '无固定网格'}
- 辉光色：`{st['glow']}`，暗角强度 `{st['vignette']}`

底板由 `core/StyleKit.tsx` 的 `<StyleStage slug="{f['slug']}">` 渲染，纯 CSS 渐变 / 内联样式实现，逐帧确定，禁用 `Math.random()`。

## 5. 动作质感

- 观感：{mo['feel']}
- 缓动：`{mo['easing']}`，入场 `{mo['spawn']}`
- 运动密度：**{mo['density']}**（低 = 留白多、动作少；高 = 持续有元素在动）
- 基准帧率：{mo['fps']}fps

> 画风只定「动起来是什么质感」；具体哪个元素在什么时候动，仍由台词锚点 `at(i)` 决定。

## 6. 镜头语法

{f['camera']}

## 7. 适用 / 不适用 / 触发词

- **适合**：{good}
- **不适合**：{bad}
- **触发词**：{trig}

## 8. 不变量（不可协商）

{inv}

## 9. 反模式 / 坑

{pit}

## 10. 与动效库组合

1. 阶段 4 分镜：按台词触发词从 `motion-lib/INDEX.md` 挑 **1 个主动作/章**。
2. 阶段 5 搭画面：`<StyleStage slug="{f['slug']}">` 包住整页，内部照常用 `MotionKit.tsx` 的组件。
3. 取色：`getStyle("{f['slug']}").palette.accent` 传给动效组件的 `color` / `style` prop；**不要改动 MotionKit 源码**。
4. 推荐先试：{rec}。
5. 一整支片**只用一个画风**，不要每页换皮；要换就整片重定，不是混搭。

可运行示例见同目录 `demo.tsx`（`StyleStage` + 标题 + 示例卡 + 一处确定性入场动作）。

## 11. 质检（三帧抽查）

- 动作起点前 1 帧：底板已就位，主体尚未出现。
- 起点后 2 帧：色板、字体、网格/材质全部生效，无溢出。
- 结果停稳帧：强调色只落在最重要的元素上，暗角 / 辉光不压字幕条。
- 另查：`Math.random()` 零命中；H 组装饰 450 帧后完全卸载；整片只出现一个画风 slug。
"""


def render_demo(f):
    slug = f["slug"]
    cn = f["cn"]
    return f'''import React from "react";
import {{ AbsoluteFill, interpolate, useCurrentFrame }} from "remotion";
import {{ StyleStage, StyledTitle, StyledBody, getStyle }} from "../../core/StyleKit";

// {cn} · 最小可运行示例：画风底板 + 一处确定性入场动作
// generated by scripts/build_styles.py from scripts/styles.json; do not edit by hand
export const Demo: React.FC = () => {{
  const frame = useCurrentFrame();
  const t = getStyle("{slug}");
  const rise = interpolate(frame, [0, 18], [28, 0], {{ extrapolateRight: "clamp" }});
  const fade = interpolate(frame, [0, 14], [0, 1], {{ extrapolateRight: "clamp" }});
  const bar = interpolate(frame, [12, 42], [0, 1], {{ extrapolateRight: "clamp" }});

  return (
    <StyleStage slug="{slug}">
      <AbsoluteFill style={{{{ justifyContent: "center", padding: "0 140px" }}}}>
        <div style={{{{ opacity: fade, transform: `translateY(${{rise}}px)` }}}}>
          <StyledTitle slug="{slug}">{cn}</StyledTitle>
          <StyledBody slug="{slug}" style={{{{ marginTop: 28 }}}}>
            {{t.signature}}
          </StyledBody>
          <div style={{{{ marginTop: 56, width: 640, height: 10, background: t.palette.line, borderRadius: 5 }}}}>
            <div style={{{{ width: `${{bar * 100}}%`, height: "100%", background: t.palette.accent, borderRadius: 5 }}}} />
          </div>
          <div style={{{{ marginTop: 26, fontFamily: t.fonts.mono, fontSize: 26, color: t.palette.dim }}}}>
            {slug} · stage {{t.stage.type}} · 30fps
          </div>
        </div>
      </AbsoluteFill>
    </StyleStage>
  );
}};

export default Demo;
'''


def render_index(data, fulls):
    cats = data["categories"]
    lines = [
        "# 画风索引 · Style Index",
        "",
        "按**这支片整体要呈现什么气质**选一个画风，一整支片只用一个。动作另从 `motion-lib/INDEX.md` 挑，两者正交。",
        "",
        "Select one look for the whole film; pick motions separately from `motion-lib/INDEX.md`.",
        "",
        HEADER_MD,
        "",
        f"共 **{len(fulls)}** 个画风 / **{len(cats)}** 类。选中一个 → 读 `styles/<slug>/STYLE.md` → 用 `core/StyleKit.tsx` 的 `<StyleStage>` 落地。",
        "",
    ]
    by_cat = {}
    for f in fulls:
        by_cat.setdefault(f["cat"], []).append(f)
    for c in cats:
        lines += [f"## {c['cn']} · {c['en']}", "", f"> {c['desc']}", "",
                  "| 画风 / Style | slug | 底板 | 强调色 | 适合 | 触发词 |", "|---|---|---|---|---|---|"]
        for f in by_cat[c["id"]]:
            lines.append(
                f"| {f['cn']} · {f['en']} | [`{f['slug']}`]({f['slug']}/STYLE.md) "
                f"| `{f['stage']['type']}` | `{f['palette']['accent']}` "
                f"| {'、'.join(f['goodFor'][:2])} | {'、'.join(f['triggers'][:2])} |"
            )
        lines.append("")
    lines += [
        "## 用法",
        "",
        "1. 阶段 4 分镜：按主题与触发词从本表定 **1 个画风**，写进配方卡；一整支片不换皮。",
        "2. 阶段 5 搭画面：拷 `core/StyleKit.tsx` + `core/style-tokens.ts` 进 `src/components/`；`<StyleStage slug=\"...\">` 包住整页。",
        "3. 阶段 4/5 选动作：从 `motion-lib/INDEX.md` 按台词触发词挑 1 个主动作/章，`delay` 一律 `at(i)`。",
        "4. 取色：`getStyle(slug).palette.accent` 传给动效组件，不改 MotionKit 源码。",
        "5. 抽帧质检：起点前 1 帧 / 起点后 2 帧 / 结果停稳帧，见每张卡 §11。",
        "6. 想改画风或做自己的：见 `MY-STYLES.md`，成品放 `~/remotion-my-styles/<slug>/`，重跑本脚本即可并入索引。",
        "",
    ]
    return "\n".join(lines)


def render_tokens_ts(fulls):
    obj = json.dumps({f["slug"]: f for f in fulls}, ensure_ascii=False, indent=2)
    return f'''{HEADER_TS}

export type StyleToken = {{
  slug: string;
  cn: string;
  en: string;
  cat: string;
  catCn: string;
  catEn: string;
  signature: string;
  palette: {{
    bg: string; surface: string; surface2: string; text: string; dim: string;
    accent: string; accent2: string; line: string; problem: string;
  }};
  fonts: {{ display: string; body: string; mono: string; weight: number; tracking: string }};
  stage: {{ type: string; typeCn: string; texture: string; grid: number; glow: string; vignette: number }};
  motion: {{ feel: string; easing: string; spawn: string; density: string; fps: number }};
  camera: string;
  goodFor: string[];
  badFor: string[];
  triggers: string[];
  invariants: string[];
  pitfalls: string[];
  recommendedMotions: string[];
}};

export const STYLE_TOKENS: Record<string, StyleToken> = {obj};

export const STYLE_SLUGS: string[] = Object.keys(STYLE_TOKENS);
'''


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    fulls = [build_full(s, data) for s in data["styles"]]
    STYLES_DIR.mkdir(parents=True, exist_ok=True)
    CORE_DIR.mkdir(parents=True, exist_ok=True)

    for f in fulls:
        d = STYLES_DIR / f["slug"]
        d.mkdir(parents=True, exist_ok=True)
        (d / "style.json").write_text(json.dumps(f, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        (d / "STYLE.md").write_text(render_style_md(f), encoding="utf-8")
        (d / "demo.tsx").write_text(render_demo(f), encoding="utf-8")

    (STYLES_DIR / "INDEX.md").write_text(render_index(data, fulls), encoding="utf-8")
    (CORE_DIR / "style-tokens.ts").write_text(render_tokens_ts(fulls), encoding="utf-8")

    print(f"generated {len(fulls)} styles / {len(data['categories'])} categories")
    print(f"  styles/<slug>/: STYLE.md + style.json + demo.tsx  ({len(fulls) * 3} files)")
    print("  styles/INDEX.md")
    print("  core/style-tokens.ts")


if __name__ == "__main__":
    main()
